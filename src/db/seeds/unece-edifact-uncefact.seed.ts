export async function seedUneceEdifactAndXmlCatalogs(): Promise<{
  edifactCount: number;
  uncefactXmlCount: number;
}> {
  const now = new Date();

  for (const row of OFFICIAL_EDIFACT_CATALOG) {
    const [
      code,
      nameEn,
      nameEs,
      functionalDomain,
      isLogisticsCore,
      senders,
      receivers,
      liveEngine,
    ] = row;

    await db
      .insert(edifactMessageTypes)
      .values({
        code,
        nameEn,
        nameEs,
        functionalDomain,
        isLogisticsCore,
        typicalSenderTypes: senders ? [...senders] : [],
        typicalReceiverTypes: receivers ? [...receivers] : [],
        directoryVersion: "D.23B",
        supportsLiveEngine: Boolean(liveEngine),
        createdAt: now,
        updatedAt: now,
      })
      .onConflictDoUpdate({
        target: edifactMessageTypes.code,
        set: {
          nameEn,
          nameEs,
          functionalDomain,
          isLogisticsCore,
          typicalSenderTypes: senders ? [...senders] : [],
          typicalReceiverTypes: receivers ? [...receivers] : [],
          supportsLiveEngine: Boolean(liveEngine),
          updatedAt: now,
        },
      });
  }

  for (const schema of OFFICIAL_UNCEFACT_XML_SCHEMAS) {
    await db
      .insert(uncefactXmlSchemas)
      .values({
        code: schema.code,
        name: schema.name,
        standardFamily: schema.standardFamily,
        releaseVersion: schema.releaseVersion,
        rootElement: schema.rootElement,
        namespaceUri: schema.namespaceUri,
        schemaUrl: schema.schemaUrl,
        edifactEquivalents: [...schema.edifactEquivalents],
        applicableEntityTypes: [...schema.applicableEntityTypes],
        supportsLiveGenerator: schema.supportsLiveGenerator,
        description: schema.description,
        createdAt: now,
        updatedAt: now,
      })
      .onConflictDoUpdate({
        target: uncefactXmlSchemas.code,
        set: {
          name: schema.name,
          standardFamily: schema.standardFamily,
          releaseVersion: schema.releaseVersion,
          rootElement: schema.rootElement,
          namespaceUri: schema.namespaceUri,
          schemaUrl: schema.schemaUrl,
          edifactEquivalents: [...schema.edifactEquivalents],
          applicableEntityTypes: [...schema.applicableEntityTypes],
          supportsLiveGenerator: schema.supportsLiveGenerator,
          description: schema.description,
          updatedAt: now,
        },
      });
  }

  console.log(
    `[Seed:UNECE] Upserted ${OFFICIAL_EDIFACT_CATALOG.length} UN/EDIFACT message types and ${OFFICIAL_UNCEFACT_XML_SCHEMAS.length} UN/CEFACT XML schemas.`,
  );

  return {
    edifactCount: OFFICIAL_EDIFACT_CATALOG.length,
    uncefactXmlCount: OFFICIAL_UNCEFACT_XML_SCHEMAS.length,
  };
}
