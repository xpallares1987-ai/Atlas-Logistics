export async function seedUnlocodeLocations(): Promise<void> {
  console.log("🌍 Seeding canonical UNECE UN/LOCODE Locations...");
  for (const item of CANONICAL_UNLOCODES) {
    await db
      .insert(unlocodeLocations)
      .values(item)
      .onConflictDoUpdate({
        target: unlocodeLocations.unLocode,
        set: {
          name: item.name,
          nameWoDiacritics: item.nameWoDiacritics,
          countryCode: item.countryCode,
          subdivisionCode: item.subdivisionCode,
          functionClassifier: item.functionClassifier,
          isPort: item.isPort,
          isRailTerminal: item.isRailTerminal,
          isRoadTerminal: item.isRoadTerminal,
          isAirport: item.isAirport,
          isPostalHub: item.isPostalHub,
          isMultimodalIcd: item.isMultimodalIcd,
          isBorderCrossing: item.isBorderCrossing,
          status: item.status,
          iataCode: item.iataCode,
          rawCoordinates: item.rawCoordinates,
          latitude: item.latitude,
          longitude: item.longitude,
          remarks: item.remarks,
        },
      });
  }
  console.log(
    `✅ Seeded ${CANONICAL_UNLOCODES.length} UNECE UN/LOCODE Locations.`,
  );
}
