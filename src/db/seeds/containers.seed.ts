export async function seedContainerIsoTypes(): Promise<void> {
  console.log(
    "📦 Seeding canonical Container ISO Types (ISO 668 / ISO 6346)...",
  );
  for (const item of CANONICAL_CONTAINER_ISO_TYPES) {
    await db
      .insert(containerIsoTypes)
      .values(item)
      .onConflictDoUpdate({
        target: containerIsoTypes.isoCode,
        set: {
          industryCode: item.industryCode,
          category: item.category,
          tareWeightKg: item.tareWeightKg,
          maxPayloadKg: item.maxPayloadKg,
          maxGrossWeightKg: item.maxGrossWeightKg,
          cubicCapacityCbm: item.cubicCapacityCbm,
          teuFactor: item.teuFactor,
          description: item.description,
        },
      });
  }
  console.log(
    `✅ Seeded ${CANONICAL_CONTAINER_ISO_TYPES.length} Container ISO Types.`,
  );
}
