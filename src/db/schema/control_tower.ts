import {
  sqliteTable,
  text,
  integer,
  real,
  index,
} from "drizzle-orm/sqlite-core";
import { sql } from "drizzle-orm";
import { commonAuditFields } from "./_common.js";
import { shipments } from "./operations.js";
import { trackedAssets } from "./iot_telemetry.js";
