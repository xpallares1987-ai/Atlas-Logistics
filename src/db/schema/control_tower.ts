import { users } from "./core.js";

/**
 * Control Tower Incidents / Disruptions across all transport modes
 */
export const controlTowerIncidents = sqliteTable(
  "control_tower_incidents",
  {
    id: text("id").primaryKey(),
    incidentNumber: text("incident_number").notNull().unique(), // e.g. "INC-2026-0814"
    shipmentId: text("shipment_id").references(() => shipments.id),
    assetId: text("asset_id").references(() => trackedAssets.id),
    incidentType: text("incident_type").notNull(), // PORT_CONGESTION, CANAL_BLOCKAGE, VESSEL_DELAY, COLD_CHAIN_BREACH, CUSTOMS_HOLD, CARRIER_DISPUTE, ROAD_ACCIDENT, WEATHER_STORM
    severity: text("severity").notNull(), // LOW, MEDIUM, HIGH, CRITICAL
    title: text("title").notNull(),
    description: text("description").notNull(),
    locationName: text("location_name"),
    locationLat: real("location_lat"),
    locationLng: real("location_lng"),
    status: text("status").notNull().default("OPEN"), // OPEN, ANALYZING, PENDING_APPROVAL, AUTO_RESOLVED, RESOLVED, CANCELLED
    autoResolved: integer("auto_resolved", { mode: "boolean" })
      .notNull()
      .default(false),
    impactAmountEur: real("impact_amount_eur").notNull().default(0),
    delayHours: real("delay_hours").notNull().default(0),
    slaDeadline: text("sla_deadline"), // ISO string
    assignedTo: text("assigned_to").references(() => users.id),
    resolutionAction: text("resolution_action"),
    resolvedAt: text("resolved_at"),
    resolvedBy: text("resolved_by"),
    createdAt: text("created_at")
      .notNull()
      .default(sql`CURRENT_TIMESTAMP`),
    updatedAt: text("updated_at")
      .notNull()
      .default(sql`CURRENT_TIMESTAMP`),
  },
  (table) => ({
    statusIdx: index("idx_ct_incidents_status").on(table.status),
    severityIdx: index("idx_ct_incidents_severity").on(table.severity),
  }),
);

/**
 * Algorithmic Rerouting Alternative Options generated by DynamicReroutingEngine
 */
export const incidentRerouteOptions = sqliteTable(
  "incident_reroute_options",
  {
    id: text("id").primaryKey(),
    incidentId: text("incident_id")
      .notNull()
      .references(() => controlTowerIncidents.id, { onDelete: "cascade" }),
    optionName: text("option_name").notNull(), // e.g. "Corredor Ferroviario Transpirenaico", "Desvío Vía Cabo de Buena Esperanza"
    transportMode: text("transport_mode").notNull(), // OCEAN, RAIL_INTERMODAL, AIR_CARGO, ROAD_EXPRESS, MULTIMODAL_FEEDER
    corridorDescription: text("corridor_description").notNull(),
    etaDeltaHours: real("eta_delta_hours").notNull(), // Negative means saves time, positive means delay
    costDeltaEur: real("cost_delta_eur").notNull(), // Additional cost or saving
    co2DeltaKg: real("co2_delta_kg").notNull(), // Carbon variance
    feasibilityScore: integer("feasibility_score").notNull().default(85), // 0 to 100
    isRecommended: integer("is_recommended", { mode: "boolean" })
      .notNull()
      .default(false),
    executionStatus: text("execution_status").notNull().default("PROPOSED"), // PROPOSED, ACCEPTED, REJECTED, EXECUTED
    legsJson: text("legs_json"), // JSON stringified legs breakdown
    createdAt: text("created_at")
      .notNull()
      .default(sql`CURRENT_TIMESTAMP`),
  },
  (table) => ({
    incidentIdx: index("idx_reroute_incident_id").on(table.incidentId),
  }),
);

/**
 * EU ICS2 Pre-Arrival Safety & Security Customs Declarations (Release 3)
 */
export const customsIcs2Declarations = sqliteTable(
  "customs_ics2_declarations",
  {
    id: text("id").primaryKey(),
    mrn: text("mrn").notNull().unique(), // Movement Reference Number (e.g. 26ES000001928472B3)
    shipmentId: text("shipment_id").references(() => shipments.id),
    declarationType: text("declaration_type").notNull().default("ENS"), // ENS (Entry Summary Declaration), CUSDEC
    filingStatus: text("filing_status").notNull().default("SUBMITTED"), // DRAFT, SUBMITTED, ACCEPTED, HELD_FOR_INSPECTION, CLEARED
    riskCircuit: text("risk_circuit").notNull().default("GREEN"), // GREEN (Levante Inmediato), ORANGE (Revisión Documental), RED (Inspección Física)
    declarantEori: text("declarant_eori").notNull(), // e.g. "ESB99482716"
    customsOfficeCode: text("customs_office_code").notNull(), // e.g. "ES004611" (Valencia Marítima)
    securityAssessmentScore: integer("security_assessment_score")
      .notNull()
      .default(98), // 0-100
    submittedAt: text("submitted_at").notNull(),
    clearedAt: text("cleared_at"),
    notes: text("notes"),
    createdAt: text("created_at")
      .notNull()
      .default(sql`CURRENT_TIMESTAMP`),
  },
  (table) => ({
    mrnIdx: index("idx_ics2_mrn").on(table.mrn),
    riskCircuitIdx: index("idx_ics2_circuit").on(table.riskCircuit),
  }),
);

/**
 * Automated 3-Way Match Freight Audit Line Disputes
 */
export const freightAuditDisputes = sqliteTable(
  "freight_audit_disputes",
  {
    id: text("id").primaryKey(),
    disputeCode: text("dispute_code").notNull().unique(), // e.g. "DSP-2026-0042"
    invoiceLineId: text("invoice_line_id").references(
      () => carrierInvoiceLines.id,
    ),
    carrierInvoiceId: text("carrier_invoice_id").references(
      () => carrierInvoices.id,
    ),
    shipmentId: text("shipment_id").references(() => shipments.id),
    claimedAmount: real("claimed_amount").notNull(),
    expectedAmount: real("expected_amount").notNull(),
    disputedAmount: real("disputed_amount").notNull(),
    reason: text("reason").notNull(), // UNJUSTIFIED_DEMURRAGE, BAF_INDEX_MISMATCH, DUPLICATE_THC, INCORRECT_CURRENCY_CONVERSION
    status: text("status").notNull().default("OPEN"), // OPEN, SUBMITTED_TO_CARRIER, WON, SETTLED, WITHDRAWN
    carrierResponseDate: text("carrier_response_date"),
    resolutionNote: text("resolution_note"),
    debitNoteNumber: text("debit_note_number"),
    createdAt: text("created_at")
      .notNull()
      .default(sql`CURRENT_TIMESTAMP`),
  },
  (table) => ({
    disputeStatusIdx: index("idx_dispute_status").on(table.status),
  }),
);
