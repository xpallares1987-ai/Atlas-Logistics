/**
 * @file ResolveIncident.tsx
 * @description Dialog for approving multimodal rerouting options or resolving supply chain incidents.
 * Enforces mandatory resolution justification and audit logging before unblocking shipments.
 * @module @atlas/frontend/components/ControlTower/Modal
 */

import React from "react";
import { ShieldAlert, X, CheckCircle2 } from "lucide-react";
import { ResolutionJustificationSelect } from "../../common/ResolutionJustificationSelect.js";
import type { ControlTowerIncident } from "../../../types/control-tower.types.js";

export interface ResolveIncidentModalProps {
  incident: ControlTowerIncident | null;
  onClose: () => void;
  onResolve: (optionId?: string) => void;
  isResolving: boolean;
  resolutionNote: string;
  onResolutionNoteChange: (note: string) => void;
}

export const ResolveIncident: React.FC<ResolveIncidentModalProps> = ({
  incident,
  onClose,
  onResolve,
  isResolving,
  resolutionNote,
  onResolutionNoteChange,
}) => {
  if (!incident) return null;

  return (
    <div className="fixed inset-0 bg-slate-950/80 backdrop-blur-sm z-50 flex items-center justify-center p-4">
      <div className="bg-slate-900 border border-slate-700 rounded-2xl max-w-2xl w-full p-6 shadow-2xl flex flex-col gap-4 text-xs">
        <div className="flex items-center justify-between pb-3 border-b border-slate-800">
          <div className="flex items-center gap-2">
            <ShieldAlert size={20} className="text-rose-400" />
            <h3 className="text-base font-bold text-white">
              Resolución de Incidencia: {incident.incidentNumber}
            </h3>
          </div>
          <button onClick={onClose} className="text-slate-400 hover:text-white">
            <X size={18} />
          </button>
        </div>

        <div className="bg-slate-800/60 p-3 rounded-lg">
          <h4 className="font-semibold text-white">{incident.title}</h4>
          <p className="text-slate-300 mt-1">{incident.description}</p>
          <div className="flex gap-4 text-slate-400 mt-2 text-[11px]">
            <span>📍 {incident.locationName}</span>
            <span>⏱️ Retraso: +{incident.delayHours}h</span>
            <span>💶 Impacto: €{incident.impactAmountEur}</span>
          </div>
        </div>

        {/* Reroute Options Generated by AI */}
        <div>
          <h4 className="text-xs font-bold text-indigo-400 uppercase tracking-wider mb-2">
            Alternativas de Re-enrutamiento Multimodal
          </h4>
          <div className="flex flex-col gap-2.5">
            {incident.rerouteOptions && incident.rerouteOptions.length > 0 ? (
              incident.rerouteOptions.map((opt: any) => (
                <div
                  key={opt.id}
                  className="bg-slate-800 border border-slate-700 hover:border-indigo-500 rounded-xl p-3.5 flex flex-col md:flex-row md:items-center justify-between gap-3 transition-colors"
                >
                  <div className="max-w-md">
                    <div className="flex items-center gap-2">
                      <span className="font-bold text-white text-xs">
                        {opt.optionName || opt.label}
                      </span>
                      {(opt.isRecommended || opt.recommended) && (
                        <span className="text-[9px] font-black bg-emerald-500/20 text-emerald-400 border border-emerald-500/30 px-2 py-0.5 rounded-full">
                          RECOMENDADA
                        </span>
                      )}
                    </div>
                    <p className="text-[11px] text-slate-300 mt-1">
                      {opt.corridorDescription || opt.description}
                    </p>
                    <div className="flex flex-wrap items-center gap-3 text-[10px] text-slate-400 mt-2">
                      <span
                        className={
                          (opt.etaDeltaHours ?? opt.delayDeltaHours) < 0
                            ? "text-emerald-400 font-bold"
                            : "text-amber-400"
                        }
                      >
                        ⏱️ ETA:{" "}
                        {(opt.etaDeltaHours ?? opt.delayDeltaHours) > 0
                          ? "+"
                          : ""}
                        {opt.etaDeltaHours ?? opt.delayDeltaHours}h
                      </span>
                      <span className="text-slate-300">
                        💶 Coste: +€{opt.costDeltaEur}
                      </span>
                      <span
                        className={
                          opt.co2DeltaKg < 0
                            ? "text-emerald-400"
                            : "text-rose-400"
                        }
                      >
                        🌿 CO2: {opt.co2DeltaKg > 0 ? "+" : ""}
                        {opt.co2DeltaKg}kg
                      </span>
                      {opt.feasibilityScore !== undefined && (
                        <span className="text-indigo-400 font-bold">
                          Factibilidad: {opt.feasibilityScore}%
                        </span>
                      )}
                    </div>
                  </div>

                  <button
                    onClick={() => onResolve(opt.id)}
                    disabled={isResolving}
                    className="px-3 py-1.5 text-xs font-bold rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white shrink-0 shadow transition-colors"
                  >
                    Aprobar y Ejecutar
                  </button>
                </div>
              ))
            ) : (
              <p className="text-slate-500 text-xs py-2">
                No hay alternativas pre-generadas. Introduce una acción manual
                abajo.
              </p>
            )}
          </div>
        </div>

        {/* Predefined Resolution Protocol Form */}
        <div className="flex flex-col gap-3 pt-3 border-t border-slate-800">
          <ResolutionJustificationSelect
            id="control-tower-resolution"
            value={resolutionNote}
            onChange={onResolutionNoteChange}
          />
          <div className="flex justify-end">
            <button
              onClick={() => onResolve()}
              disabled={isResolving || !resolutionNote}
              className="px-5 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white font-bold transition-all disabled:opacity-50 flex items-center gap-2 shadow-lg shadow-emerald-600/20"
            >
              <CheckCircle2 size={16} />
              <span>Resolver Incidencia</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};

export const ResolveIncidentModal = ResolveIncident;
